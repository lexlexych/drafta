-- drafts.workflow_run_id — за какой прогон держится генерация черновика.
--
-- Кнопка «стоп» под спиннером раньше опиралась на `cancelOn` Inngest: действие
-- эмитило `draft/generate.cancelled`, платформа сопоставляла событие с живым
-- прогоном по `conversationId` и снимала его на границе шага. В Workflow SDK
-- отмена адресная — `getRun(runId).cancel()`, — поэтому runId нужно где-то
-- держать, и строка черновика для этого ровно то место: она уже создаётся
-- первым шагом прогона, живёт столько же и гасится тем же действием.
--
-- Поведение кнопки не меняется: пользовательская отмена по-прежнему случается
-- в БД (черновик переводится в `discarded`, это и разблокирует поле ввода во
-- всех вкладках), а снятие прогона идёт следом и лишь экономит остаток работы.
-- Отсюда nullable: у черновиков, созданных до этой миграции, и у любых будущих
-- строк, дошедших до `ready`, ссылка на прогон не обязана существовать.
--
-- Docs: docs/architecture/18-workflows.md,
--       docs/architecture/07-data-flows.md#62-генерация-черновика

alter table public.drafts
  add column workflow_run_id text;

comment on column public.drafts.workflow_run_id is
  'runId прогона generate-draft (`wrun_…`), который сейчас пишет этот черновик. Нужен кнопке «стоп»: по нему вызывается run.cancel(). Null — прогон уже завершился или черновик создан до перехода на Workflows.';
