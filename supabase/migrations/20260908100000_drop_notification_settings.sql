-- Убирает таблицу `notification_settings` вместе с режимом «дайджест».
--
-- У контура уведомлений осталась одна частота: push уходит на каждое новое
-- входящее. Выбора между «мгновенно» и «сводкой по интервалу» больше нет, а
-- значит таблице нечего хранить: все её колонки (`mode`,
-- `digest_interval_minutes`, `last_digest_at`) обслуживали только дайджест.
-- Вместе с ней из кода ушли cron-функция `push-digest` и раздел настроек
-- «Уведомления» — подписка устройства на push переехала в «Приложение»
-- (docs/architecture/11-realtime-pwa.md).
--
-- Сами подписки живут в `push_subscriptions` и остаются нетронутыми: получатель
-- push теперь определяется наличием подписки, а не строкой настроек.
--
-- `cascade` снимает политики RLS и индексы таблицы; `if exists` — чтобы
-- миграция применялась и на окружении, где таблицы уже нет.
drop table if exists public.notification_settings cascade;
