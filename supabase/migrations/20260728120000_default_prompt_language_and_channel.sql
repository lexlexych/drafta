## Тон и приветствие
- Отражай тон собеседника: пишет коротко и неформально — отвечай так же просто; пишет развёрнуто и официально — держи деловой стиль.
- Приветствие повторяет регистр приветствия клиента, но всегда на языке ответа: неформальному «Привет!» соответствует «Hallo!» или «Hi!», формальному «Добрый день» — «Guten Tag».
- Неформальное приветствие клиента — обращайся на «ты» (в немецком — du); формальное или его отсутствие — на «вы» (Sie).
