-- Системный промпт workspace вместо тона/языка/подписи + категория «Личное».
--
-- Тон, язык и подпись были тремя узкими полями, которые уходили в промпт сырым
-- JSON-объектом и не давали пользователю влиять ни на роль, ни на выбор
-- приветствия, ни на формат ответа. Вместо них — два редактируемых системных
-- промпта: для черновиков переписки и для черновиков комментариев. Дефолтные
-- шаблоны лежат в дефолтах колонок, поэтому новый workspace получает их без
-- участия приложения; те же тексты продублированы в lib/ai/default-prompts.ts
-- (совпадение проверяет lib/system-prompt-migration.test.ts).
--
-- Заземление и контракт NEEDS_MANUAL_REVIEW остаются в неизменяемой секции
-- промпта (groundingRules() в lib/ai/prompt.ts): шаблон объясняет их по-русски,
-- но удаление этих строк пользователем заземление не отключает.
--
-- Воркспейсов в базе ещё нет, поэтому бэкфилла нет: только DDL и замена
-- create_workspace.

