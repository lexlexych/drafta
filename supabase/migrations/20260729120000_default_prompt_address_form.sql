-- Дефолтные шаблоны системных промптов: язык ответа и форма обращения.
--
-- Русский вопрос «Вы продаете что-то кроме одежды?» получал немецкий черновик
-- на «du»: база знаний немецкая и написана на du, и модель принимала её язык и
-- её обращение за сигнал. Ни то, ни другое сигналом не является — язык и форму
-- обращения задаёт только сам клиент.
--
-- Обращение вынесено из блока про тон в собственный раздел: там оно висело
-- одной строкой, привязанной к приветствию, и вопрос без приветствия оставался
-- без правила. Теперь форма определяется по местоимениям клиента и переносится
-- в язык ответа, а не выбирается в нём заново.
--
-- Те же правила продублированы в неизменяемой секции 2 промпта
-- (languageAndAddressRules() в lib/ai/prompt.ts), поэтому пользователь,
-- переписавший шаблон, их не отключает.
--
-- Меняются только дефолты колонок: правка уже применённой миграции ничего не
-- изменила бы в базе. Бэкфилла нет намеренно — system_prompt редактируемый,
-- и перезапись чужого текста стёрла бы настройки workspace. Тексты дословно
-- совпадают с lib/ai/default-prompts.ts (lib/system-prompt-migration.test.ts).

